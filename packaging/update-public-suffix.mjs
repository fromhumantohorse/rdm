// Download https://publicsuffix.org/list/public_suffix_list.dat to a local file, then run:
// node packaging/update-public-suffix.mjs <downloaded-file>
// Review and commit the generated snapshot with the extension's next release. No runtime fetch.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { domainToASCII } from "node:url";

const bytes = readFileSync(process.argv[2]);
const text = bytes.toString("utf8");
if (!["BEGIN ICANN DOMAINS", "END PRIVATE DOMAINS"].every((marker) => text.includes(marker))) throw new Error("Not a complete Public Suffix List");
const rules = text.split(/\r?\n/).map((line) => line.trim()).filter((line) => line && !line.startsWith("//")).map((rule) => {
  const prefix = rule.startsWith("!") ? "!" : rule.startsWith("*.") ? "*." : "";
  const domain = domainToASCII(rule.slice(prefix.length));
  if (!domain || !/^[a-z0-9_.-]+$/.test(domain)) throw new Error(`Invalid suffix rule ${rule}`);
  return prefix + domain;
});
if (rules.length < 5000) throw new Error("Public Suffix List is unexpectedly short");
const version = text.match(/^\/\/ VERSION: (.+)$/m)?.[1];
if (!version) throw new Error("Public Suffix List has no version");
const hash = createHash("sha256").update(bytes).digest("hex");
const groups = [];
for (let at = 0; at < rules.length; at += 8) groups.push(rules.slice(at, at + 8).join(" "));
writeFileSync(new URL("../extension/public-suffix-data.js", import.meta.url), `// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.
// Generated by packaging/update-public-suffix.mjs. ICANN + PRIVATE sections, ASCII hosts.
// Source: https://publicsuffix.org/list/public_suffix_list.dat
// VERSION: ${version.trim()}
// SHA256: ${hash}
export const suffixRules = new Set(\`
${groups.join("\n")}
\`.trim().split(/\\s+/));
`);
console.log(`Bundled ${rules.length} public suffix rules (${version.trim()}, SHA256 ${hash})`);
